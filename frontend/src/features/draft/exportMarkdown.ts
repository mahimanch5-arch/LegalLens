import type { AssistantMessage } from '@/api/types';
import { docTitle } from '@/lib/format';

export const DRAFT_MARKING = 'UNREVIEWED AI DRAFT — prepared by Legal Lens. Attorney review is required before any use. This is not legal advice.';
export const DISCLAIMER = 'Generated by Legal Lens from the documents listed above. An attorney work-product aid, not legal advice; the reviewing attorney is responsible for its use.';

function sourcesSection(m: AssistantMessage): string {
  if (m.citations.length === 0) return '';
  const lines = [...m.citations]
    .sort((a, b) => a.n - b.n)
    .map((c) => `[${c.n}] ${docTitle(c.documentName)}, p. ${c.page}${c.section ? `, ${c.section}` : ''} — “${c.quote.replace(/\s+/g, ' ')}”`);
  return ['## Sources', '', ...lines].join('\n');
}

/** Markdown export of any assistant output (FR-24). Drafts carry the review marking top and bottom (FR-23). */
export function toMarkdown(m: AssistantMessage, question?: string): string {
  const parts: string[] = [];
  const isDraft = m.intent === 'draft' && !!m.draft;

  if (isDraft) parts.push(`> **${DRAFT_MARKING}**`);

  if (m.refusal) {
    parts.push(`**Not answerable from the documents searched (${m.refusal.scopeLabel}).**`, m.refusal.reason);
  } else if (m.summary) {
    parts.push(`# Summary — ${docTitle(m.summary.documentName)}`);
    for (const s of m.summary.sections) {
      parts.push(`## ${s.title}`);
      parts.push(
        s.fields
          .map((f) => `- **${f.label}:** ${f.value ?? '_Not addressed in this document._'}${f.citations.map((n) => ` [${n}]`).join('')}${f.flag ? ` ⚠ ${f.flag}` : ''}`)
          .join('\n'),
      );
    }
    const cov = m.summary.coverage;
    parts.push(`_Coverage: ${cov.pagesCovered} of ${cov.pagesTotal} pages read${cov.note ? `. ${cov.note}` : '.'}_`);
  } else {
    if (question && !isDraft) parts.push(`**Question:** ${question}`);
    parts.push(m.answerMd.trim());
  }

  if (m.status === 'incomplete') parts.push('_This response was interrupted and is incomplete._');
  const src = sourcesSection(m);
  if (src) parts.push(src);
  if (m.scopeUsed) parts.push(`_Scope searched: ${m.scopeUsed.label}._`);
  parts.push(`---\n_${isDraft ? DRAFT_MARKING : DISCLAIMER}_`);
  return parts.join('\n\n') + '\n';
}

export function downloadMarkdown(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.replace(/[\\/:*?"<>|]+/g, '-').slice(0, 100) + '.md';
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
